// ---- write / check -------------------------------------------------------
const outputs = [
  [join(root, "src/styles/tokens.css"), css],
  [join(root, "design-system/contrast.json"), JSON.stringify(results, null, 2) + "\n"],
  [join(root, "design-system/index.html"), html],
];
let stale = false;
for (const [file, content] of outputs) {
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) stale = true;
  } else writeFileSync(file, content);
}

for (const r of results) {
  if (!r.pass || !check) console.log(`${r.pass ? "PASS" : "FAIL"} ${r.theme.padEnd(5)} ${(r.fg + " on " + r.bg).padEnd(30)} ${r.ratio.toFixed(2)}:1 (needs ${r.min})`);
}
const failed = results.filter((r) => !r.pass);
if (check && stale) console.error("tokens.css, contrast.json or index.html is stale: run `npm run tokens`.");
if (check && (stale || failed.length)) process.exit(1);
console.log(`${results.length - failed.length}/${results.length} pairs pass AA.`);
