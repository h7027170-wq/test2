// Generates src/styles/tokens.css and design-system/index.html from design-system/tokens.json,
// and checks every declared text/background pair against WCAG AA in both themes.
// Usage: node scripts/tokens.mjs [--check]   (--check: fail if a file is stale or a pair fails)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design-system/tokens.json"), "utf8"));
const check = process.argv.includes("--check");
const themes = ["light", "dark"];

// ---- contrast ------------------------------------------------------------
function luminance(hex) {
  const n = hex.replace("#", "");
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}
export function ratio(a, b) {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}

// Validate: both themes declare the same keys, and every contrast pair uses 6-digit hex values.
const hex = /^#[0-9a-f]{6}$/i;
const [lightKeys, darkKeys] = themes.map((th) => Object.keys(tokens.color[th]).sort().join());
if (lightKeys !== darkKeys) throw new Error("light and dark themes must declare the same colour keys");
for (const p of tokens.color.pairs) {
  for (const th of themes) {
    for (const k of [p.fg, p.bg]) {
      if (!hex.test(tokens.color[th][k] ?? "")) throw new Error(`pair ${p.fg}/${p.bg}: ${th}.${k} must be a 6-digit hex colour`);
    }
  }
  if (!(p.min === 3 || p.min === 4.5)) throw new Error(`pair ${p.fg}/${p.bg}: min must be 3 or 4.5`);
}

const results = [];
for (const theme of themes) {
  const c = tokens.color[theme];
  for (const p of tokens.color.pairs) {
    const r = ratio(c[p.fg], c[p.bg]);
    results.push({ theme, ...p, fgHex: c[p.fg], bgHex: c[p.bg], ratio: Math.round(r * 100) / 100, pass: r >= p.min });
  }
}

